import { existsSync, globSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { Plugin } from 'vite'

const routesDirectory = 'src/routes'

function generateRscRouteTypes(root: string) {
  const routeRoot = join(root, routesDirectory)
  const routes = globSync('**/page.tsx', { cwd: routeRoot, withFileTypes: true })
    .filter((file) => file.isFile())
    .map((file) => {
      const segments = relative(routeRoot, file.parentPath).split(sep).filter(Boolean)
      const params = segments.flatMap((segment) => {
        const match = /^\[([^\]]+)\]$/.exec(segment)
        return match ? [JSON.stringify(match[1])] : []
      })
      return `    ${JSON.stringify(`/${segments.join('/')}`)}: ${params.join(' | ') || 'never'}`
    })
    .sort()

  const declaration = [
    '// Generated by generate-rsc-route-types.ts.',
    'export {}',
    "declare module 'void/routes' {",
    '  interface RoutePathMap {',
    ...routes,
    '  }',
    '}',
    ''
  ].join('\n')
  const outputDirectory = join(root, '.void')
  const output = join(outputDirectory, 'rsc-routes.d.ts')

  if (!existsSync(output) || readFileSync(output, 'utf8') !== declaration) {
    mkdirSync(outputDirectory, { recursive: true })
    writeFileSync(output, declaration)
  }
}

export function rscRouteTypesPlugin(): Plugin {
  return {
    name: 'rsc-route-types',
    apply: (_config, { isPreview }) => !isPreview,
    configResolved(config) {
      generateRscRouteTypes(config.root)
    },
    configureServer(server) {
      const { root } = server.config
      const routePrefix = `${join(root, routesDirectory)}${sep}`
      const update = (file: string) => {
        if (file.startsWith(routePrefix) && file.endsWith(`${sep}page.tsx`)) {
          generateRscRouteTypes(root)
        }
      }
      server.watcher.on('add', update).on('unlink', update)
    }
  }
}

if (import.meta.main) {
  generateRscRouteTypes(fileURLToPath(new URL('..', import.meta.url)))
}
