import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptPath = fileURLToPath(import.meta.url)
const scriptDir = path.dirname(scriptPath)
const repoRoot = path.resolve(scriptDir, '..')
const routesDir = path.join(repoRoot, 'src', 'routes')
const outputFile = path.join(repoRoot, 'src', 'page-routes.generated.ts')

export async function generatePageRoutes() {
  const routeFiles = await collectPageFiles(routesDir)
  const routes = routeFiles
    .map((filePath) => createRouteDefinition(filePath))
    .sort((a, b) => a.file.localeCompare(b.file))

  ensureUniqueRouteKeys(routes)

  const nextContents = renderGeneratedFile(routes)
  const currentContents = await fs.readFile(outputFile, 'utf8').catch(() => null)
  const changed = currentContents !== nextContents

  if (changed) {
    await fs.writeFile(outputFile, nextContents)
  }

  return { changed, routes }
}

async function collectPageFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name)

    if (entry.isDirectory()) {
      files.push(...(await collectPageFiles(entryPath)))
      continue
    }

    if (entry.isFile() && entry.name === 'page.tsx') {
      files.push(entryPath)
    }
  }

  return files
}

function createRouteDefinition(filePath) {
  const relativeFilePath = path
    .relative(path.join(repoRoot, 'src'), filePath)
    .split(path.sep)
    .join('/')
  const routeDirectory = path.posix.dirname(relativeFilePath)
  const segments =
    routeDirectory === 'routes' ? [] : routeDirectory.slice('routes/'.length).split('/')
  const pattern = segments.length === 0 ? '/' : `/${segments.join('/')}`
  const params = segments.flatMap((segment) => {
    const dynamicMatch = /^\[([^\]]+)\]$/.exec(segment)
    return dynamicMatch ? [dynamicMatch[1]] : []
  })

  return {
    file: `./${relativeFilePath}`,
    key: createRouteKey(segments),
    params,
    pattern,
    segments
  }
}

function createRouteKey(segments) {
  if (segments.length === 0) {
    return 'home'
  }

  const words = segments.flatMap(segmentToWords)
  const [firstWord = 'route', ...remainingWords] = words
  const key = `${firstWord}${remainingWords.map(capitalize).join('')}`.replace(/^\d/, 'route$&')

  return key || 'route'
}

function segmentToWords(segment) {
  const normalized = segment.replace(/^\[([^\]]+)\]$/, '$1')
  return normalized
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((word) => word.toLowerCase())
}

function capitalize(value) {
  return value.charAt(0).toUpperCase() + value.slice(1)
}

function ensureUniqueRouteKeys(routes) {
  const seen = new Set()

  for (const route of routes) {
    if (seen.has(route.key)) {
      throw new Error(`Duplicate generated route key "${route.key}" for pattern ${route.pattern}`)
    }

    seen.add(route.key)
  }
}

function renderGeneratedFile(routes) {
  const imports = [
    'import {',
    '  brandRouteHref,',
    '  encodeRouteSegment,',
    '  withRouteSearch,',
    '  type RouteHref,',
    '  type RouteHrefOptions',
    "} from '@/framework/page-routes.ts'",
    ''
  ]

  const definitions = [
    'export const pageRouteDefinitions = [',
    ...routes.map((route, index) => renderRouteDefinition(route, index === routes.length - 1)),
    '] as const',
    ''
  ]

  const types = [
    'export type PageRouteDefinition = (typeof pageRouteDefinitions)[number]',
    "export type PageRouteKey = PageRouteDefinition['key']",
    "export type PageRoutePattern = PageRouteDefinition['pattern']",
    '',
    ...renderParamsTypeLines(routes),
    '',
    'export type PageRouteHref<P extends PageRoutePattern = PageRoutePattern> = RouteHref<P>',
    ''
  ]

  const helpers = [
    'export const pageRoutes = {',
    ...routes.map((route, index) => renderRouteHelper(route, index === routes.length - 1)),
    '} as const',
    ''
  ]

  return [
    '// This file is generated by scripts/generate-page-routes.mjs.',
    '// Do not edit directly.',
    '',
    ...imports,
    ...definitions,
    ...types,
    ...helpers
  ].join('\n')
}

function renderRouteDefinition(route, isLast) {
  const segments = `[${route.segments.map((segment) => quote(segment)).join(', ')}] as const`
  const suffix = isLast ? '' : ','
  const inline = `{ file: ${quote(route.file)}, key: ${quote(route.key)}, pattern: ${quote(route.pattern)}, segments: ${segments} }${suffix}`

  if (inline.length <= 88) {
    return `  ${inline}`
  }

  return [
    '  {',
    `    file: ${quote(route.file)},`,
    `    key: ${quote(route.key)},`,
    `    pattern: ${quote(route.pattern)},`,
    `    segments: ${segments}`,
    `  }${suffix}`
  ].join('\n')
}

function renderParamsTypeLines(routes) {
  const [firstRoute, ...remainingRoutes] = routes
  const lines = [
    `export type PageRouteParams<P extends PageRoutePattern = PageRoutePattern> = P extends ${quote(firstRoute.pattern)}`,
    `  ? ${renderParamsObject(routes[0].params)}`
  ]

  for (const [index, route] of remainingRoutes.entries()) {
    const indentation = '  '.repeat(index + 1)
    lines.push(`${indentation}: P extends ${quote(route.pattern)}`)
    lines.push(`${indentation}  ? ${renderParamsObject(route.params)}`)
  }

  lines.push(`${'  '.repeat(routes.length)}: never`)

  return lines
}

function renderRouteHelper(route, isLast) {
  const hrefSignature =
    route.params.length === 0
      ? 'href(options?: RouteHrefOptions)'
      : `href(params: ${renderParamsObject(route.params)}, options?: RouteHrefOptions)`

  const pathnameExpression =
    route.segments.length === 0
      ? "'/'"
      : `\`${route.segments
          .map((segment) => {
            const dynamicMatch = /^\[([^\]]+)\]$/.exec(segment)
            if (!dynamicMatch) {
              return `/${segment}`
            }

            return `/\${encodeRouteSegment(params.${dynamicMatch[1]})}`
          })
          .join('')}\``

  const returnExpression = `brandRouteHref<${quote(route.pattern)}>(withRouteSearch(${pathnameExpression}, options?.search))`
  const returnLines =
    returnExpression.length <= 88
      ? [`      return ${returnExpression}`]
      : [
          `      return brandRouteHref<${quote(route.pattern)}>(`,
          `        withRouteSearch(${pathnameExpression}, options?.search)`,
          '      )'
        ]

  return [
    `  ${route.key}: {`,
    `    key: ${quote(route.key)},`,
    `    pattern: ${quote(route.pattern)} as const,`,
    `    ${hrefSignature} {`,
    ...returnLines,
    '    }',
    `  }${isLast ? '' : ','}`
  ].join('\n')
}

function renderParamsObject(params) {
  if (params.length === 0) {
    return 'Record<string, never>'
  }

  return `{ ${params.map((param) => `${formatPropertyKey(param)}: string`).join('; ')} }`
}

function formatPropertyKey(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : quote(value)
}

function quote(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
}

if (process.argv[1] === scriptPath) {
  await generatePageRoutes()
}
